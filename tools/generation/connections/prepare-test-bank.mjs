// Pinned typed conversion. Deliberately excludes authored board examples.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {checkBank} from './validate.mjs';
const bytes=readFileSync(new URL('./pilot.json',import.meta.url));
const bank=JSON.parse(bytes), result=checkBank(bank);
if(result.errors.length) throw new Error(result.errors.join('\n'));
const hash=createHash('sha256').update(bytes).digest('hex');
const text=value=>JSON.stringify(value).replaceAll('$','\\$');
const relation=r=>`        ConnectionsRelation(
            id = ${text(r.id)}, label = ${text(r.label)}, explanation = ${text(r.explanation)},
            relationType = ${text(r.relationType)}, prerequisites = ${text(r.prerequisites)},
            wordplay = ${r.wordplay}, revision = ${r.revision}, reviewStatus = ${text(r.reviewStatus)},
            members = listOf(
${r.members.map(m=>`                ConnectionsMember(${text(m.tile)}, ${text(m.sense)}),`).join('\n')}
            ),
        ),`;
const provenance=bank.provenance.source+'; '+bank.provenance.rights+'; human review pending';
const fields=values=>values.map(v=>`${v.length}:${v}`).join('');
const canonicalRelation=r=>fields([r.id,r.label,r.explanation,r.relationType,r.prerequisites,String(r.wordplay),String(r.revision),r.reviewStatus,...[...r.members].sort((a,b)=>a.tile<b.tile?-1:a.tile>b.tile?1:0).flatMap(m=>[m.tile,m.sense])]);
const canonicalRelations=relations=>fields([...relations].sort((a,b)=>a.id<b.id?-1:a.id>b.id?1:0).map(canonicalRelation));
const typedHash=createHash('sha256').update(fields([String(bank.schemaVersion),bank.version,provenance,hash,canonicalRelations(bank.categories),canonicalRelations(bank.decoyRelations)])).digest('hex');
const output=`// Generated by tools/generation/connections/prepare-test-bank.mjs; do not edit.
// Pilot JSON SHA-256: ${hash}. Contains no finished board examples.
package dev.clean.words.generators.connections

object BundledConnectionsBank {
    const val contentSha256 = ${text(typedHash)}
    const val sourceSha256 = ${text(hash)}
    const val version = ${text(bank.version)}
    val bank: ConnectionsBank by lazy { ConnectionsBank(
        version = ${text(bank.version)},
        provenance = ${text(provenance)},
        schemaVersion = ${bank.schemaVersion}, sourceSha256 = ${text(hash)},
        categories = listOf(
${bank.categories.map(relation).join('\n')}
        ),
        decoyRelations = listOf(
${bank.decoyRelations.map(relation).join('\n')}
        ),
    ) }
}
`;
const targets=[
  [new URL('../../../app/src/main/java/dev/clean/words/generators/connections/BundledConnectionsBank.kt',import.meta.url),output],
  [new URL('../../../app/src/test/java/dev/clean/words/generators/connections/ConnectionsPilot.kt',import.meta.url),`// Generated test alias; benchmark and runtime consume exactly the same typed bank.\npackage dev.clean.words.generators.connections\n\nobject ConnectionsPilot { val bank get() = BundledConnectionsBank.bank }\n`],
];
for(const [target,value] of targets) {
  if(process.argv.includes('--check')) {
    if(!existsSync(target)||readFileSync(target,'utf8')!==value) throw new Error('Typed bank conversion is stale');
  } else writeFileSync(target,value);
}
console.log(`Pinned bank ${process.argv.includes('--check')?'current':'written'}: source=${hash} typed=${typedHash}`);
