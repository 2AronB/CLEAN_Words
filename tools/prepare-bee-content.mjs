// Original theme seeds/goal vocabulary with public-domain ENABLE validation.
import fs from 'node:fs';
import crypto from 'node:crypto';
const source = 'app/src/main/assets/dictionaries/enable1.txt';
const raw = fs.readFileSync(source);
const dictionary = new Set(raw.toString('utf8').split(/\r?\n/).map(w => w.trim().toUpperCase()).filter(w => /^[A-Z]+$/.test(w)));
const version = `ENABLE1-sha256:${crypto.createHash('sha256').update(raw).digest('hex')}`;
const seeds = [
  ['central','CENTRAL','A','CENTRAL LATER ALERT ALTER CLEAR CLEAN CRANE LEARN EARL EARN NEAR CARE RACE LACE LATE RATE TEAR REAL AREA CATER CREATE CAREER'],
  ['reading','READING','A','READING GARDEN GRAIN DRAIN RANGE ANGER DANGER GEAR EARN NEAR DEAR READ DARE RAIN GAIN RAID AREA AGAIN GRADE GRAND'],
  ['kitchen','KITCHEN','I','KITCHEN THICKEN THICK THINK CHICK TICKET TICK KITE KNIT NICK NICE INCH THIN ITCH HINT HIKE HITCH CHIN'],
  ['picture','PICTURE','E','PICTURE RECIPE PRICE PIECE CRIER TRICE CREEP RECITE RECUT TRUCE CUTTER TRIPE PURE PIER RICE RITE TIRE TREE PEER EPIC ERECT UPPER'],
  ['journey','JOURNEY','O','JOURNEY ENJOY YOUR YORE NOUN NOON NONE NEON EURO JOEY'],
  ['capture','CAPTURE','A','CAPTURE CARPET CRATER CRATE TRACE REACT CATER CAPER TAPER PAPER PEAR PARE RARE RATE CARE RACE AREA ACUTE ACCURATE APPEAR'],
  ['another','ANOTHER','A','ANOTHER ANTHER EARTH HEART HATER HATE HEAT RATE TARE TEAR NEAR EARN ARENA ANON ANTE OATH TART ROAN RANT RATHER THROAT HATTER TANNER'],
  ['subject','SUBJECT','E','SUBJECT CUBE CUBES CUTE SUET SECT JEST JETS TUBES TUBE SUBSET BEET BEETS BEST BESET CUTEST'],
  ['blanket','BLANKET','A','BLANKET BLANK BLEAK BLEAT TABLE TAKEN BAKE LAKE LATE TALE TAKE TANK BANK BEAN LEAN LANE BEAT BEAK ABLE TEAK BANE BATTLE LATTE BANANA'],
  ['country','COUNTRY','O','COUNTRY COUNT COURT COUNTY CORNY CRONY COOT COTTON CROON TOON TROT TORN YOUR TOUR UNTO ONTO ROOT TYCOON COCOON CONTOUR TRYOUT OUTCRY OUTRUN'],
];
let output = `package dev.clean.words.games.bee\n\nimport dev.clean.words.core.PuzzleRecord\n\n/** Generated by tools/prepare-bee-content.mjs from pinned public-domain ENABLE1. */\nobject BeeContent {\n    const val dictionaryVersion = "${version}"\n    val puzzles: List<PuzzleRecord> = listOf(\n`;
for (const [id, seed, center, goalText] of seeds) {
  const letters = [...new Set(seed)].sort().join('');
  const matches = word => word.length >= 4 && word.includes(center) && [...word].every(c => letters.includes(c));
  const goals = [...new Set(goalText.split(' '))].sort();
  const invalid = goals.filter(word => !matches(word) || !dictionary.has(word));
  if (letters.length!==7 || invalid.length) throw Error(`${id}: invalid goal words ${invalid.join(', ')}`);
  const valid = [...dictionary].filter(matches).sort();
  output += `        BeePuzzle("${letters}", '${center}',\n            "${goals.join(',')}".split(',').toSet(),\n            "${valid.join(',')}".split(',').toSet(), dictionaryVersion, BeePuzzle.WORD_COUNT_SCORING).snapshot("bee-${id}-v2"),\n`;
  console.log(`${id}: ${goals.length} goal words, ${valid.length} accepted words`);
}
output += `    )\n}\n`;
fs.mkdirSync('app/src/main/java/dev/clean/words/games/bee',{recursive:true});
fs.writeFileSync('app/src/main/java/dev/clean/words/games/bee/BeeContent.kt',output);
