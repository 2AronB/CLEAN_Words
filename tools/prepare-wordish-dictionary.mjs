// Derive the accepted five-letter guess list; no network or dependencies.
// Run: node tools/prepare-wordish-dictionary.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const source = new URL('../app/src/main/assets/dictionaries/enable1.txt', import.meta.url);
const target = new URL('../app/src/main/java/dev/clean/words/games/wordish/WordishDictionary.kt', import.meta.url);
const bytes = await readFile(source);
const hash = createHash('sha256').update(bytes).digest('hex');
const words = [...new Set(bytes.toString('utf8').split(/\r?\n/).filter(w => /^[a-z]{5}$/.test(w)).map(w => w.toUpperCase()))].sort();
if (words.length < 5000) throw new Error(`Unexpected dictionary size: ${words.length}`);
const chunks = [];
for (let i = 0; i < words.length; i += 400) chunks.push(words.slice(i, i + 400).join(' '));
const code = `// Generated by tools/prepare-wordish-dictionary.mjs; do not hand-edit.
// ENABLE source SHA-256: ${hash}
package dev.clean.words.games.wordish

internal object WordishDictionary {
    const val version = "enable-five-v1"
    const val sourceSha256 = "${hash}"
    val words: Set<String> by lazy {
        listOf(\n${chunks.map(c => `            "${c}"`).join(',\n')}\n        ).flatMap { it.split(' ') }.toSet()
    }
}
`;
await mkdir(new URL('.', target), { recursive: true });
await writeFile(target, code, 'utf8');
console.log(`Generated ${words.length} five-letter guesses; source SHA-256 ${hash}`);
